function resolveSecretFile(params) {
  const fromEnv = process.env[params.envKey];
  if (typeof fromEnv === "string" && fromEnv.trim().length > 0) {
    return fromEnv.trim();
  }

  const fallbackAbsolutePath = path.resolve(__dirname, params.fallbackRelativePath);
  if (fs.existsSync(fallbackAbsolutePath)) {
    return params.fallbackRelativePath;
  }

  return undefined;
}

// A JSON file of the form { "owner": "...", "projectId": "..." }.
function resolveExpoProject(params) {
  const file = resolveSecretFile(params);
  if (!file) {
    return undefined;
  }
  const { owner, projectId } = JSON.parse(fs.readFileSync(path.resolve(__dirname, file), "utf8"));
  return { owner, projectId };
}

